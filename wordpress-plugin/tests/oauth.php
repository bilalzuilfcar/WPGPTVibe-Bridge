<?php
require __DIR__.'/run.php';
check(file_exists(dirname(__DIR__).'/includes/class-oauth.php'),'direct OAuth connection exists');
require dirname(__DIR__).'/includes/vendor-autoload.php';
require dirname(__DIR__).'/includes/class-oauth-storage.php';
require dirname(__DIR__).'/includes/class-oauth.php';
$storage=new WPGPTVibe_OAuth_Storage();
$client=WPGPTVibe_OAuth::register_client(['redirect_uris'=>['https://chatgpt.com/connector_platform_oauth_redirect']]);
check(!empty($client['client_id']),'OAuth client registered');
rejects(fn()=>WPGPTVibe_OAuth::register_client(['redirect_uris'=>['https://evil.example/callback']]),'callback');
$verifier=str_repeat('a',64);$challenge=rtrim(strtr(base64_encode(hash('sha256',$verifier,true)),'+/','-_'),'=');
$params=['client_id'=>$client['client_id'],'redirect_uri'=>$client['redirect_uris'][0],'response_type'=>'code','state'=>'random-state','scope'=>'site:read pages:read pages:write','resource'=>WPGPTVibe_OAuth::resource(),'code_challenge'=>$challenge,'code_challenge_method'=>'S256'];
WPGPTVibe_OAuth::validate_authorization($params);
rejects(fn()=>WPGPTVibe_OAuth::validate_authorization(array_merge($params,['code_challenge_method'=>'plain'])),'S256');
rejects(fn()=>WPGPTVibe_OAuth::validate_authorization(array_merge($params,['redirect_uri'=>$params['redirect_uri'].'/other'])),'callback');
rejects(fn()=>WPGPTVibe_OAuth::validate_authorization(array_merge($params,['resource'=>'https://wrong.example/mcp'])),'resource');
$code=WPGPTVibe_OAuth::issue_code($params,1);
$exchange=['grant_type'=>'authorization_code','code'=>$code,'redirect_uri'=>$params['redirect_uri'],'client_id'=>$params['client_id'],'code_verifier'=>$verifier,'resource'=>$params['resource']];
$bad=WPGPTVibe_OAuth::exchange(array_merge($exchange,['code_verifier'=>str_repeat('b',64)]));
check($bad['status']===400,'incorrect PKCE verifier rejected');
$token=WPGPTVibe_OAuth::exchange($exchange);
check($token['status']===200&&!empty($token['body']['access_token']),'PKCE authorization code exchanged');
check(WPGPTVibe_OAuth::identity($token['body']['access_token'])['user_id']===1,'token resolves authorized WordPress user');
$again=WPGPTVibe_OAuth::exchange($exchange);check($again['status']===400,'authorization code cannot be replayed');
$storage->context=array_intersect_key($storage->getAccessToken($token['body']['access_token']),array_flip(['resource','issuer','epoch','family']));
$storage->setAccessToken('expired',$client['client_id'],1,time()-10,'site:read');
rejects(fn()=>WPGPTVibe_OAuth::identity('expired'),'expired');
WPGPTVibe_OAuth::disconnect();
rejects(fn()=>WPGPTVibe_OAuth::identity($token['body']['access_token']),'revoked');
